"""Sample PdfChartReport that exercises every page type.

Run from the repository root:

    .venv/Scripts/python.exe examples/reporting/pdf_chart_report_sample.py [output.pdf]

The PDF goes to the system temp folder unless an output path is given. All
numbers are synthetic.
"""

import argparse
import tempfile
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from quantbullet.reporting import PdfChartReport
from quantbullet.reporting._reportlab_utils import PdfColumnFormat, PdfColumnMeta

DEFAULT_OUTPUT = Path(tempfile.gettempdir()) / "pdf_chart_report_sample.pdf"


def summary_table() -> tuple[pd.DataFrame, list[PdfColumnMeta]]:
    frame = pd.DataFrame({
        "segment": ["Alpha", "Beta", "Gamma", "Delta", "Total"],
        "count": [1240, 860, 410, 220, 2730],
        "share": [0.924, 0.712, 0.580, 0.495, 0.768],
        "score": [12.0, 24.0, np.nan, 40.0, 21.0],
    })
    schema = [
        PdfColumnMeta("segment", "Segment", PdfColumnFormat(align="LEFT")),
        PdfColumnMeta("count", "Count", PdfColumnFormat(decimals=0, comma=True, align="RIGHT")),
        PdfColumnMeta("share", "Share", PdfColumnFormat(formatter=lambda v: f"{v:.1%}", align="RIGHT")),
        PdfColumnMeta("score", "Score", PdfColumnFormat(decimals=1, missing_label="n/a", align="RIGHT")),
    ]
    return frame, schema


def build(output: Path) -> Path:
    rng = np.random.default_rng(7)
    report = PdfChartReport(
        output,
        title="Sample Model Report",
        header=("{title}", "", "{section}"),
        footer=("Synthetic data", "", "Page {page} of {pages}"),
    )
    report.add_title_page(
        "Sample Model Report",
        subtitle="PdfChartReport page types",
        notes=["All numbers are synthetic.", "Generated by examples/reporting/pdf_chart_report_sample.py."],
    )

    # A section without a divider page: its outline entry points at its first page.
    report.add_section("Fit summary", divider=False)
    frame, schema = summary_table()
    with report.page("Fit summary", subtitle="Text, a schema table, bullets, a chart and a caption") as page:
        page.text(
            "Blocks added before the chart stack down from the title. Blocks added after it "
            "stack up from the bottom of the body, and the chart takes the height left between. "
            "Paragraphs wrap to the body width, and newlines start new lines."
        )
        page.heading("Summary")
        page.table(frame, schema=schema, col_widths=[0.4, 0.2, 0.2, 0.2], bold_rows=[-1])
        page.heading("Notes")
        page.bullets([
            "Wrapped bullet lines align with the item text rather than the bullet, so long "
            "items stay readable when they run over several lines of the body width.",
            "Text is plain: $5 and $6 are not read as math.",
        ])
        ax = page.chart()
        steps = np.arange(1, 25)
        ax.plot(steps, 0.05 + 0.02 * np.sin(steps / 4) + rng.normal(0, 0.003, steps.size), label="Actual")
        ax.plot(steps, 0.05 + 0.02 * np.sin(steps / 4), label="Model")
        ax.set_xlabel("Month")
        ax.set_ylabel("Rate")
        ax.set_title("Actual vs model")
        ax.legend()
        page.caption("Source: synthetic series.")

    with report.page("Lookup tables") as page:
        page.table(
            [["Alpha", "Largest segment"], ["Beta", "Second segment"], ["Gamma", "Smaller segment"]],
            columns=["Name", "Note"], align="left", col_widths=[0.24, 0.76],
        )
        page.caption("Rows given without columns have no header row:")
        page.table([["Rows", 1234567], ["Ratio", 0.123456]], align=["left", "right"])

    # A section with a divider page, then a grid that overflows onto a second page.
    report.add_section("Diagnostics", subtitle="Implied errors by feature")
    report.new_page(layout=(3, 3), title="Numerical - Implied Errors", subtitle="Eleven panels on a 3x3 grid")
    for index in range(11):
        ax = report.get_next_ax()
        ax.plot(np.arange(10), rng.normal(size=10).cumsum() * 1000)
        ax.set_title(f"Feature {index}")
        ax.set_xlabel("Bucket")

    # A figure built elsewhere: its suptitle becomes the page title.
    fig, axes = plt.subplots(1, 2, layout="constrained")
    axes[0].bar(["A", "B", "C"], [3, 5, 2])
    axes[1].scatter(rng.normal(size=50), rng.normal(size=50), s=8)
    fig.suptitle("Figure with constrained layout")
    report.add_figure(fig)

    fig, ax = plt.subplots()
    ax.plot([0, 1], [0, 1])
    ax.set_ylabel("Value")
    report.add_figure(fig, title="Figure without a layout engine")

    report.save()
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", nargs="?", type=Path, default=DEFAULT_OUTPUT, help="PDF path to write")
    args = parser.parse_args()
    print(f"Wrote {build(args.output)}")


if __name__ == "__main__":
    main()
